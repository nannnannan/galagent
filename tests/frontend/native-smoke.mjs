// Uses the owned GalAgent Electron CDP endpoint. No model fixture or API key.
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
const {chromium}=await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE||((process.env.USERPROFILE || "C:/Users/User").replace(/\\/g, "/") + "/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs")).href);
const browser=await chromium.connectOverCDP(process.env.GALAGENT_CDP||'http://127.0.0.1:9224');
const pages=browser.contexts().flatMap(c=>c.pages());
const chat=pages.find(p=>p.url().includes('view=chat'));
const pet=pages.find(p=>p.url().includes('view=pet'));
assert.ok(chat&&pet,'both native views must exist');
const original=await chat.evaluate(()=>window.galagent.getSnapshot());
assert.ok(original.identity&&original.settings,'native bridge must return real service snapshot');
const report=[];
async function dispatch(command){const result=await chat.evaluate(c=>window.galagent.dispatch(c),command);assert.equal(result.ok,true,result.error);return result;}
await dispatch({type:'chat.cancel'});report.push('native cancel bridge');
await dispatch({type:'settings.update',settings:{quietUntil:Date.now()+60000}});
await chat.waitForFunction(()=>document.body.classList.contains('quiet-mode'));
assert.ok(await chat.locator('#quiet').textContent().then(s=>s.includes('恢复主动')));
await dispatch({type:'settings.update',settings:{quietUntil:original.settings.quietUntil}});report.push('quiet state updates across native renderer');
const text=`[UI验收样本 ${Date.now()}] 用户测试桌面记忆入口`;
for(const item of original.memories.filter(m=>m.valid&&m.text.startsWith('[UI验收样本 ')))await dispatch({type:'memory.delete',id:item.id});
await dispatch({type:'memory.remember',text});
let state=await chat.evaluate(()=>window.galagent.getSnapshot());
const memory=state.memories.find(m=>m.text===text&&m.valid);
assert.ok(memory,'remember must persist explicit user-authored memory');
await chat.locator('[data-page=memory]').click();
await chat.locator('#content-page').getByText(text,{exact:true}).waitFor();
await dispatch({type:'memory.correct',id:memory.id,text:`${text} 已纠正`});
state=await chat.evaluate(()=>window.galagent.getSnapshot());
assert.ok(state.memories.some(m=>m.valid&&m.text===`${text} 已纠正`));
const corrected=state.memories.find(m=>m.valid&&m.text===`${text} 已纠正`);
await dispatch({type:'memory.delete',id:corrected.id});
state=await chat.evaluate(()=>window.galagent.getSnapshot());
assert.equal(state.memories.some(m=>m.valid&&m.text.startsWith(text)),false);
report.push('real remember / correction / delete (synthetic sample cleaned)');
await chat.locator('[data-page=chat]').click();
await chat.locator('#input').fill('尚未发送的中文验收草稿');
await chat.evaluate(()=>window.nativeInputNode=document.querySelector('#input'));
await dispatch({type:'settings.update',settings:{reducedMotion:!original.settings.reducedMotion}});
assert.equal(await chat.evaluate(()=>window.nativeInputNode===document.querySelector('#input')),true);
assert.equal(await chat.locator('#input').inputValue(),'尚未发送的中文验收草稿');
await chat.locator('#input').fill('');
await dispatch({type:'settings.update',settings:{reducedMotion:original.settings.reducedMotion}});report.push('native snapshots preserve Chinese input DOM');
const before=await pet.evaluate(()=>({x:screenX,y:screenY}));
await pet.evaluate(()=>window.galagent.dispatch({type:'shell.drag',dx:-10,dy:-10}));
await pet.waitForTimeout(100);
const after=await pet.evaluate(()=>({x:screenX,y:screenY}));
assert.ok(before.x!==after.x||before.y!==after.y,'native shell drag must move pet window');
await pet.evaluate(delta=>window.galagent.dispatch({type:'shell.drag',dx:delta.x,dy:delta.y}),{x:before.x-after.x,y:before.y-after.y});report.push('native pet movement and position restoration');
await mkdir('docs/evidence',{recursive:true});
await chat.waitForTimeout(350);
await chat.screenshot({path:'docs/evidence/UI-native.png'});
await pet.screenshot({path:'docs/evidence/UI-pet-native.png',omitBackground:true});
const cdp=await chat.context().newCDPSession(chat);
await cdp.send('Emulation.setDeviceMetricsOverride',{width:860,height:600,deviceScaleFactor:1,mobile:false});
assert.equal(await chat.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.ok(await chat.locator('#composer').isVisible());
await cdp.send('Emulation.clearDeviceMetricsOverride');
await cdp.detach();report.push('minimum 860 × 600 layout has visible composer and no horizontal overflow');
await writeFile('tests/frontend/evidence/native-ui.json',JSON.stringify({at:new Date().toISOString(),scope:'owned native Electron app; no model call or key',passed:report},null,2));
console.log(report.join('\n'));
// Disconnect only. The desktop app belongs to the parent task and stays alive.
await browser.close();
